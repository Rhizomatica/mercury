#!/usr/bin/env python3
"""DVB-S2 short-frame LDPC codes (16200 bits) as codec2 H_rows/H_cols arrays.

    utils/ldpc_dvbs2_gen.py <out dir> C2_3:10800 C3_4:11880 ...

The parity-check matrix is read off GNU Radio's DVB-S2 LDPC encoder
(gr-dtv): the code is systematic with an accumulator over the parity bits,
so encoding a single information bit and undoing the accumulator gives that
bit's column.  The code is quasi-cyclic in groups of 360 bits, so only the
first bit of each group is encoded and the rest follow by the shift
q = parity bits / 360.  Rate 3/5 reproduces modem/freedv/H_16200_9720.c
exactly (H_rows identical; H_cols the same sets, in another order).

Needs GNU Radio with gr-dtv (python3 -c "from gnuradio import dtv").
"""
import sys
import numpy as np
from gnuradio import gr, blocks, dtv

N = 16200
def derive(rate, k):
    """rows[r] = sorted 1-based info bit indices of parity check r, from the encoder."""
    npb = N - k; q = npb // 360; groups = k // 360
    frames = np.zeros(groups * k, dtype=np.uint8)
    for g in range(groups): frames[g * k + g * 360] = 1
    tb = gr.top_block()
    src = blocks.vector_source_b(frames.tolist(), False)
    enc = dtv.dvb_ldpc_bb(dtv.STANDARD_DVBS2, dtv.FECFRAME_SHORT, getattr(dtv, rate), dtv.MOD_OTHER)
    snk = blocks.vector_sink_b(); tb.connect(src, enc, snk); tb.run()
    out = np.array(snk.data(), dtype=np.uint8).reshape(groups, N)
    rows = [[] for _ in range(npb)]
    for g in range(groups):
        p = out[g, k:]
        a = p.copy(); a[1:] ^= p[:-1]          # undo the accumulator
        base = np.nonzero(a)[0]
        for m in range(360):
            for x in base:
                rows[(x + m * q) % npb].append(g * 360 + m + 1)
    return [sorted(r) for r in rows], q
def cols_of(rows, k):
    cols = [[] for _ in range(k)]
    for r, lst in enumerate(rows):
        for b in lst: cols[b - 1].append(r + 1)
    return cols
def arr(name, mat, n, w):
    flat = [mat[i][j] if j < len(mat[i]) else 0 for j in range(w) for i in range(n)]
    lines = ["    " + ", ".join(f"{v:5d}" for v in flat[i:i + 12]) + "," for i in range(0, len(flat), 12)]
    lines[-1] = lines[-1].rstrip(',')
    return f"const uint16_t {name}[] = {{\n" + "\n".join(lines) + "};\n"
def emit(rate, k, outdir):
    rows, q = derive(rate, k)
    npb = N - k; cols = cols_of(rows, k)
    wr = max(map(len, rows)); wc = max(map(len, cols)); nm = f"H_{N}_{k}"
    hdr = f"""/*
  FILE....: {nm}.h

  Static arrays for LDPC codec {nm}: the DVB-S2 short-frame code of rate
  {rate[1]}/{rate[3]} (ETSI EN 302 307, 16200 bits, {k} information bits), read off
  GNU Radio's DVB-S2 LDPC encoder by utils/ldpc_dvbs2_gen.py.
*/

#define {nm}_NUMBERPARITYBITS {npb}
#define {nm}_MAX_ROW_WEIGHT {wr}
#define {nm}_CODELENGTH {N}
#define {nm}_NUMBERROWSHCOLS {k}
#define {nm}_MAX_COL_WEIGHT {wc}
#define {nm}_DEC_TYPE 0
#define {nm}_MAX_ITER 100

#include <stdint.h>

extern const uint16_t {nm}_H_rows[];
extern const uint16_t {nm}_H_cols[];
"""
    src = f"""/*
  FILE....: {nm}.c

  Static arrays for LDPC codec {nm}, generated by utils/ldpc_dvbs2_gen.py.
*/

#include "{nm}.h"

#include <stdint.h>

""" + arr(f"{nm}_H_rows", rows, npb, wr) + "\n" + arr(f"{nm}_H_cols", cols, k, wc)
    open(f"{outdir}/{nm}.h", "w").write(hdr); open(f"{outdir}/{nm}.c", "w").write(src)
    return nm, wr, wc
if __name__ == "__main__":
    out = sys.argv[1]
    for rate, k in [(s.split(':')[0], int(s.split(':')[1])) for s in sys.argv[2:]]:
        print(emit(rate, k, out))
