#!/usr/bin/env python3
"""Irregular repeat-accumulate LDPC codes by progressive edge growth, as codec2
H_rows/H_cols arrays.

    utils/ldpc_ira_peg.py <out dir> <N> <K> [info column weight] [seed]

The code has the structure codec2's decoder and encoder assume for every
code in modem/freedv (H1, as the DVB-S2 ones): H = [A | B] with B the
accumulator, parity bit j in checks j and j+1, so parity p_j = p_{j-1} xor
(the information bits of check j).  A is built by progressive edge growth
(Hu, Eleftheriou, Arnold, "Regular and irregular progressive edge-growth
Tanner graphs", IEEE Trans. IT 51(1), 2005): each information bit's edges go,
one at a time, to a check as far as possible from the bit in the graph built
so far (the accumulator's edges included), the least connected one among
those, so short cycles are avoided where they can be.  Ties are broken by a
seeded random choice, so a code is reproduced exactly from its arguments.

Written for the narrow (500 Hz) rungs, where a 16200-bit codeword would take
~20 s a frame.  The name follows codec2's: H_<K>_<N>... is not used there
consistently, so these are named H_IRA_<N>_<K>.
"""
import random
import sys
from collections import deque


def peg_ira(n, k, dv, seed):
    m = n - k
    rnd = random.Random(seed)
    chk = [[] for _ in range(m)]          # check -> variable nodes
    var = [[] for _ in range(n)]          # variable -> check nodes
    # the accumulator: parity bit j (variable k + j) in checks j and j+1
    for j in range(m):
        for c in (j, j + 1) if j + 1 < m else (j,):
            chk[c].append(k + j)
            var[k + j].append(c)
    for v in range(k):
        for e in range(dv):
            if not var[v]:
                deg = min(len(chk[c]) for c in range(m))
                c = rnd.choice([c for c in range(m) if len(chk[c]) == deg])
            else:
                # breadth-first from v: the checks reached at each depth
                seen_c = set(var[v])
                seen_v = {v}
                frontier = list(var[v])
                while True:
                    nxt_v = []
                    for c in frontier:
                        for u in chk[c]:
                            if u not in seen_v:
                                seen_v.add(u)
                                nxt_v.append(u)
                    nxt_c = []
                    for u in nxt_v:
                        for c in var[u]:
                            if c not in seen_c:
                                seen_c.add(c)
                                nxt_c.append(c)
                    if not nxt_c or len(seen_c) == m:
                        far = [c for c in range(m) if c not in seen_c]
                        if not far:            # every check reached: the last layer
                            far = frontier
                        break
                    frontier = nxt_c
                deg = min(len(chk[c]) for c in far)
                c = rnd.choice([c for c in far if len(chk[c]) == deg])
            chk[c].append(v)
            var[v].append(c)
    rows = [sorted(u + 1 for u in chk[c] if u < k) for c in range(m)]
    return rows


def arr(name, mat, n, w):
    flat = [mat[i][j] if j < len(mat[i]) else 0 for j in range(w) for i in range(n)]
    lines = ["    " + ", ".join(f"{v:5d}" for v in flat[i:i + 12]) + "," for i in range(0, len(flat), 12)]
    lines[-1] = lines[-1].rstrip(',')
    return f"const uint16_t {name}[] = {{\n" + "\n".join(lines) + "};\n"


def emit(n, k, dv, seed, outdir):
    rows = peg_ira(n, k, dv, seed)
    m = n - k
    cols = [[] for _ in range(k)]
    for r, lst in enumerate(rows):
        for b in lst:
            cols[b - 1].append(r + 1)
    wr = max(map(len, rows)); wc = max(map(len, cols)); nm = f"H_IRA_{n}_{k}"
    hdr = f"""/*
  FILE....: {nm}.h

  Static arrays for LDPC codec {nm}: an irregular repeat-accumulate code,
  {n} bits, {k} information bits, information columns of weight {dv}, placed
  by progressive edge growth (utils/ldpc_ira_peg.py {n} {k} {dv} {seed}).
*/

#define {nm}_NUMBERPARITYBITS {m}
#define {nm}_MAX_ROW_WEIGHT {wr}
#define {nm}_CODELENGTH {n}
#define {nm}_NUMBERROWSHCOLS {k}
#define {nm}_MAX_COL_WEIGHT {wc}
#define {nm}_DEC_TYPE 0
#define {nm}_MAX_ITER 100

#include <stdint.h>

extern const uint16_t {nm}_H_rows[];
extern const uint16_t {nm}_H_cols[];
"""
    src = f"""/*
  FILE....: {nm}.c

  Static arrays for LDPC codec {nm}, generated by
  utils/ldpc_ira_peg.py {n} {k} {dv} {seed}.
*/

#include "{nm}.h"

#include <stdint.h>

""" + arr(f"{nm}_H_rows", rows, m, wr) + "\n" + arr(f"{nm}_H_cols", cols, k, wc)
    open(f"{outdir}/{nm}.h", "w").write(hdr)
    open(f"{outdir}/{nm}.c", "w").write(src)
    return nm, wr, wc


if __name__ == "__main__":
    out, n, k = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
    dv = int(sys.argv[4]) if len(sys.argv) > 4 else 3
    seed = int(sys.argv[5]) if len(sys.argv) > 5 else 1
    print(emit(n, k, dv, seed, out))
